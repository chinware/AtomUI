using System;

namespace AtomUIGallery.ShowCases.Button;

public partial class ButtonDesignTokenDataGrid : GalleryReactiveUserControl<ButtonViewModel>
{
    public ButtonDesignTokenDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is ButtonViewModel viewModel)
        {
            viewModel.EnsureDesignTokenRows();
            DesignTokenDataGrid.ItemsSource = viewModel.DesignTokenRows;
        }
        else
        {
            DesignTokenDataGrid.ItemsSource = null;
        }
    }
}
