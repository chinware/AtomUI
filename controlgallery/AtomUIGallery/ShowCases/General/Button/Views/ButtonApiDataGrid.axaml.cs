using System;

namespace AtomUIGallery.ShowCases.Button;

public partial class ButtonApiDataGrid : GalleryReactiveUserControl<ButtonViewModel>
{
    public ButtonApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is ButtonViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
