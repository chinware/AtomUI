using System;

namespace AtomUIGallery.ShowCases.Alert;

public partial class AlertApiDataGrid : GalleryReactiveUserControl<AlertViewModel>
{
    public AlertApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is AlertViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
