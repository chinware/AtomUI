using System;

namespace AtomUIGallery.ShowCases.LineEdit;

public partial class LineEditDesignTokenDataGrid : GalleryReactiveUserControl<LineEditViewModel>
{
    public LineEditDesignTokenDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is LineEditViewModel viewModel)
        {
            viewModel.EnsureDesignTokenRows();
            DesignTokenDataGrid.ItemsSource = viewModel.DesignTokenRows;
        }
        else
        {
            DesignTokenDataGrid.ItemsSource = null;
        }
    }
}
