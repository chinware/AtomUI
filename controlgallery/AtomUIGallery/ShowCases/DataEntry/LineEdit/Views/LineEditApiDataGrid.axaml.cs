namespace AtomUIGallery.ShowCases.LineEdit;

public partial class LineEditApiDataGrid : GalleryReactiveUserControl<LineEditViewModel>
{
    public LineEditApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is LineEditViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
