namespace AtomUIGallery.ShowCases.AutoComplete;

public partial class AutoCompleteDesignTokenDataGrid : GalleryReactiveUserControl<AutoCompleteViewModel>
{
    public AutoCompleteDesignTokenDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is AutoCompleteViewModel viewModel)
        {
            viewModel.EnsureDesignTokenRows();
            DesignTokenDataGrid.ItemsSource = viewModel.DesignTokenRows;
        }
        else
        {
            DesignTokenDataGrid.ItemsSource = null;
        }
    }
}
