namespace AtomUIGallery.ShowCases.TreeSelect;

public partial class TreeSelectApiDataGrid : GalleryReactiveUserControl<TreeSelectViewModel>
{
    public TreeSelectApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is TreeSelectViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
