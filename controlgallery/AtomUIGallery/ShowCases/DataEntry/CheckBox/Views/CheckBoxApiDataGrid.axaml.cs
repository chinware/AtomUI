namespace AtomUIGallery.ShowCases.CheckBox;

public partial class CheckBoxApiDataGrid : GalleryReactiveUserControl<CheckBoxViewModel>
{
    public CheckBoxApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is CheckBoxViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
