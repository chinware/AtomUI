using System;

namespace AtomUIGallery.ShowCases.Menu;

public partial class MenuApiDataGrid : GalleryReactiveUserControl<MenuViewModel>
{
    public MenuApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is MenuViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
