namespace AtomUIGallery.ShowCases.Calendar;

public partial class CalendarApiDataGrid : GalleryReactiveUserControl<CalendarViewModel>
{
    public CalendarApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is CalendarViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
