namespace AtomUIGallery.ShowCases.TreeView;

public partial class TreeViewDesignTokenDataGrid : GalleryReactiveUserControl<TreeViewViewModel>
{
    public TreeViewDesignTokenDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is TreeViewViewModel viewModel)
        {
            viewModel.EnsureDesignTokenRows();
            DesignTokenDataGrid.ItemsSource = viewModel.DesignTokenRows;
        }
        else
        {
            DesignTokenDataGrid.ItemsSource = null;
        }
    }
}
