namespace AtomUIGallery.ShowCases.TreeView;

public partial class TreeViewApiDataGrid : GalleryReactiveUserControl<TreeViewViewModel>
{
    public TreeViewApiDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is TreeViewViewModel viewModel)
        {
            viewModel.EnsureApiRows();
            ApiDataGrid.ItemsSource = viewModel.ApiRows;
        }
        else
        {
            ApiDataGrid.ItemsSource = null;
        }
    }
}
