using System;

namespace AtomUIGallery.ShowCases.Empty;

public partial class EmptyDesignTokenDataGrid : GalleryReactiveUserControl<EmptyViewModel>
{
    public EmptyDesignTokenDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is EmptyViewModel viewModel)
        {
            viewModel.EnsureDesignTokenRows();
            DesignTokenDataGrid.ItemsSource = viewModel.DesignTokenRows;
        }
        else
        {
            DesignTokenDataGrid.ItemsSource = null;
        }
    }
}
