using System;

namespace AtomUIGallery.ShowCases.GroupBox;

public partial class GroupBoxDesignTokenDataGrid : GalleryReactiveUserControl<GroupBoxViewModel>
{
    public GroupBoxDesignTokenDataGrid()
    {
        InitializeComponent();
    }

    protected override void OnDataContextChanged(EventArgs e)
    {
        base.OnDataContextChanged(e);
        if (DataContext is GroupBoxViewModel viewModel)
        {
            viewModel.EnsureDesignTokenRows();
            DesignTokenDataGrid.ItemsSource = viewModel.DesignTokenRows;
        }
        else
        {
            DesignTokenDataGrid.ItemsSource = null;
        }
    }
}
