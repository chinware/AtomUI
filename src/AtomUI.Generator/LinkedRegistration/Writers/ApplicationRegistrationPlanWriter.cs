using System.Collections.Immutable;
using System.Text;
using AtomUI.Generator.LinkedRegistration.Model;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.Generator.LinkedRegistration.Writers;

internal static class ApplicationRegistrationPlanWriter
{
    internal static string Write(
        string ownerId,
        ImmutableArray<ApplicationPackagePlan> packages)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.Append("[assembly: global::System.Reflection.AssemblyMetadata(")
              .Append(SymbolDisplay.FormatLiteral(LinkedRegistrationProtocol.PlanMarkerKey, quote: true))
              .Append(", ")
              .Append(SymbolDisplay.FormatLiteral(ownerId, quote: true))
              .AppendLine(")] ");
        source.AppendLine();
        source.AppendLine("namespace AtomUI.Generated.LinkedRegistrationV1;");
        source.AppendLine();
        source.AppendLine("internal static class GeneratedApplicationRegistrationPlan");
        source.AppendLine("{");
        source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        source.AppendLine("    internal static void Install()");
        source.AppendLine("    {");
        source.Append("        global::AtomUI.Registration.AotTrimRegistrationPlanRegistry.Install(")
              .Append(SymbolDisplay.FormatLiteral(ownerId, quote: true))
              .AppendLine(", ApplyPackage);");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    private static bool ApplyPackage(");
        source.AppendLine("        global::AtomUI.IAtomUIBuilder builder,");
        source.AppendLine("        string packageId,");
        source.AppendLine("        global::AtomUI.Theme.Resources.IControlThemesProvider provider,");
        source.AppendLine("        global::System.Func<global::AtomUI.Theme.Schema.ControlTokenIdentity, bool>? includeIdentity,");
        source.AppendLine("        global::System.Func<global::System.Collections.Generic.IReadOnlyList<global::AtomUI.Theme.Schema.ControlThemeAssetDescriptor>, global::System.Collections.Generic.IReadOnlyList<global::AtomUI.Theme.Schema.ControlThemeAssetDescriptor>>? selectAssets)");
        source.AppendLine("    {");
        source.AppendLine("        switch (packageId)");
        source.AppendLine("        {");
        foreach (var package in packages)
        {
            WritePackage(source, package);
        }
        source.AppendLine("            default:");
        source.AppendLine("                return false;");
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }

    private static void WritePackage(StringBuilder source, ApplicationPackagePlan plan)
    {
        source.Append("            case ")
              .Append(SymbolDisplay.FormatLiteral(plan.PackageId, quote: true))
              .AppendLine(":");
        source.AppendLine("            {");
        if (plan.UseFullFallback)
        {
            source.Append("                global::").Append(plan.Package.FullFragmentType)
                  .Append('.').Append(plan.Package.FullFragmentMethod).AppendLine("(");
            source.AppendLine("                    builder.Theme,");
            source.AppendLine("                    provider,");
            source.AppendLine("                    includeIdentity,");
            source.AppendLine("                    selectAssets);");
        }
        else
        {
            source.AppendLine("                var packageBuilder = new global::AtomUI.Registration.AotTrimControlPackageRegistrationBuilder(");
            source.AppendLine("                    builder,");
            source.AppendLine("                    provider,");
            source.AppendLine("                    includeIdentity,");
            source.AppendLine("                    selectAssets);");
            if (plan.Package.PackageSharedFragmentType is not null)
            {
                source.Append("                global::")
                      .Append(plan.Package.PackageSharedFragmentType).Append('.')
                      .Append(plan.Package.PackageSharedFragmentMethod).AppendLine("(packageBuilder);");
            }
            foreach (var unit in plan.Units)
            {
                source.Append("                global::").Append(unit.FragmentType).Append('.')
                      .Append(unit.FragmentMethod).AppendLine("(packageBuilder);");
            }
            source.AppendLine("                packageBuilder.Register();");
        }
        source.AppendLine("                return true;");
        source.AppendLine("            }");
    }
}
