using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AtomUI.Generator;

internal sealed class GeneratedThemeSchemaWriter
{
    private const string DefaultControlCatalog = "AtomUI";
    private readonly SourceProductionContext _context;
    private readonly string _generatedNamespace;
    private readonly IReadOnlyList<SchemaTokenInfo> _globalTokens;
    private readonly IReadOnlyList<ControlTokenInfo> _controls;
    private readonly IReadOnlyList<ThemeAlgorithmInfo> _algorithms;

    internal GeneratedThemeSchemaWriter(
        SourceProductionContext context,
        string? assemblyName,
        IEnumerable<SchemaTokenInfo> globalTokens,
        IEnumerable<ControlTokenInfo> controls,
        IEnumerable<ThemeAlgorithmInfo> algorithms)
    {
        _context = context;
        _generatedNamespace = GetGeneratedNamespace(assemblyName);
        _globalTokens = globalTokens.OrderBy(static token => token.Name, StringComparer.Ordinal).ToArray();
        _controls = controls.OrderBy(static control => control.ResourceCatalog ?? DefaultControlCatalog, StringComparer.Ordinal)
                            .ThenBy(static control => control.ControlId, StringComparer.Ordinal)
                            .ToArray();
        _algorithms = algorithms.OrderBy(static algorithm => algorithm.Id, StringComparer.Ordinal)
                                .ThenBy(static algorithm => algorithm.TypeName, StringComparer.Ordinal)
                                .ToArray();
    }

    internal void Write()
    {
        _context.AddSource(
            "GeneratedThemeSchema.g.cs",
            GeneratedSourceText.From(BuildSource()));
    }

    private string BuildSource()
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("using global::AtomUI.Theme.Schema;");
        source.AppendLine();
        source.Append("namespace ").Append(_generatedNamespace).AppendLine(";");
        source.AppendLine();
        source.AppendLine("internal static class GeneratedThemeSchema");
        source.AppendLine("{");
        WriteGlobalTokens(source);
        source.AppendLine();
        WriteControls(source);
        source.AppendLine();
        WriteAlgorithms(source);
        source.AppendLine();
        source.AppendLine("    internal static global::System.Collections.Generic.IReadOnlyList<TokenDescriptor> GetGlobalTokens() => s_globalTokens;");
        source.AppendLine("    internal static global::System.Collections.Generic.IReadOnlyList<ControlTokenDescriptor> GetControls() => s_controls;");
        source.AppendLine("    internal static global::System.Collections.Generic.IReadOnlyList<ThemeAlgorithmDescriptor> GetAlgorithms() => s_algorithms;");
        source.AppendLine("}");
        return source.ToString();
    }

    private static string GetGeneratedNamespace(string? assemblyName)
    {
        if (string.IsNullOrWhiteSpace(assemblyName))
        {
            return "AtomUI.Generated";
        }

        return "AtomUI.Generated." + ToIdentifier(assemblyName!);
    }

    private static string ToIdentifier(string segment)
    {
        if (segment.Length == 0)
        {
            return "_";
        }

        var identifier = new StringBuilder(segment.Length + 1);
        if (char.IsDigit(segment[0]))
        {
            identifier.Append('_');
        }

        foreach (var character in segment)
        {
            identifier.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        }

        var result = identifier.ToString();
        return SyntaxFacts.GetKeywordKind(result) == SyntaxKind.None ? result : "_" + result;
    }

    private void WriteGlobalTokens(StringBuilder source)
    {
        source.AppendLine("    private static readonly TokenDescriptor[] s_globalTokens = new TokenDescriptor[]");
        source.AppendLine("    {");
        for (var slot = 0; slot < _globalTokens.Count; slot++)
        {
            WriteToken(
                source,
                _globalTokens[slot],
                slot,
                $"global::AtomUI.Theme.Styling.SharedTokenKind.{_globalTokens[slot].Name}");
        }
        source.AppendLine("    };");
    }

    private void WriteControls(StringBuilder source)
    {
        source.AppendLine("    private static readonly ControlTokenDescriptor[] s_controls = new ControlTokenDescriptor[]");
        source.AppendLine("    {");
        foreach (var control in _controls)
        {
            var catalog = SymbolDisplay.FormatLiteral(control.ResourceCatalog ?? DefaultControlCatalog, quote: true);
            var id = SymbolDisplay.FormatLiteral(control.ControlId!, quote: true);
            var typeName = FullyQualify(control.GetFullyQualifiedTypeName());
            source.AppendLine("        new ControlTokenDescriptor(");
            source.Append("            new ControlTokenIdentity(").Append(catalog).Append(", ").Append(id).AppendLine("),");
            source.AppendLine("            new TokenDescriptor[]");
            source.AppendLine("            {");
            var tokens = control.SchemaTokens.OrderBy(static token => token.Name, StringComparer.Ordinal).ToArray();
            for (var slot = 0; slot < tokens.Length; slot++)
            {
                var resourceKey = $"global::{control.ControlNamespace}.DesignTokens.{control.TokenKindType}.{tokens[slot].Name}";
                WriteToken(source, tokens[slot], slot, resourceKey, indentation: "                ");
            }
            source.AppendLine("            },");
            source.Append("            static () => new ").Append(typeName).AppendLine("(),");
            source.Append("            static (token, appearance) => ((").Append(typeName)
                  .AppendLine(")token).CalculateTokenValues(appearance == global::AtomUI.Theme.ThemeAppearance.Dark)),");
        }
        source.AppendLine("    };");
    }

    private void WriteAlgorithms(StringBuilder source)
    {
        source.AppendLine("    private static readonly ThemeAlgorithmDescriptor[] s_algorithms = new ThemeAlgorithmDescriptor[]");
        source.AppendLine("    {");
        foreach (var algorithm in _algorithms)
        {
            var id = SymbolDisplay.FormatLiteral(algorithm.Id, quote: true);
            source.Append("        new ThemeAlgorithmDescriptor(").Append(id)
                  .Append(", ").Append(algorithm.Revision)
                  .Append(", ThemeAppearanceEffect.").Append(algorithm.AppearanceEffect).AppendLine(",");
            source.Append("            static () => new ").Append(algorithm.TypeName).AppendLine("()),");
        }
        source.AppendLine("    };");
    }

    private static void WriteToken(
        StringBuilder source,
        SchemaTokenInfo token,
        int slot,
        string resourceKey,
        string indentation = "        ")
    {
        var name = SymbolDisplay.FormatLiteral(token.Name, quote: true);
        source.Append(indentation).Append("new TokenDescriptor(").Append(name).Append(", ").Append(slot)
              .Append(", TokenStage.").Append(token.Stage).Append(", typeof(").Append(token.ValueType)
              .Append("), ").Append(resourceKey).AppendLine(",");
        source.Append(indentation).Append("    static value => ThemeTokenValueParser.Parse<")
              .Append(token.ValueType).AppendLine(">(value),");
        source.Append(indentation).Append("    static value => ThemeTokenValueFormatter.Format((")
              .Append(token.ValueType).AppendLine(")value!),");
        source.Append(indentation).Append("    static token => ((").Append(token.DeclaringType).Append(")token).")
              .Append(token.Name).AppendLine(",");
        source.Append(indentation).Append("    static (token, value) => ((").Append(token.DeclaringType).Append(")token).")
              .Append(token.Name).Append(" = (").Append(token.ValueType).AppendLine(")value!,");
        source.Append(indentation).Append("    static token => ThemeResourceValue.Project(((")
              .Append(token.DeclaringType).Append(")token).")
              .Append(token.Name).AppendLine(")),");
    }

    private static string FullyQualify(string typeName)
    {
        return typeName.StartsWith("global::", StringComparison.Ordinal)
            ? typeName
            : $"global::{typeName}";
    }
}
