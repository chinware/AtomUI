using System.Globalization;
using System.Text;
using AtomUI.Generator.Localization.Catalog;
using Microsoft.CodeAnalysis;

namespace AtomUI.Generator.Localization;

internal static class LanguageCatalogSourceWriter
{
    internal static void Write(
        SourceProductionContext context,
        string? assemblyName,
        CompiledLanguageCatalog compiledCatalog)
    {
        var catalog = compiledCatalog.Catalog;
        context.AddSource(
            $"{catalog.MetadataName}.LanguageCatalog.g.cs",
            GeneratedSourceText.From(BuildSource(catalog)));
        context.AddSource(
            $"{catalog.MetadataName}.LanguageCatalogRegistration.g.cs",
            GeneratedSourceText.From(BuildRegistrationSource(
                assemblyName,
                compiledCatalog)));
    }

    private static string BuildSource(LanguageCatalogInfo catalog)
    {
        var extensionName = GetExtensionName(catalog.MetadataName);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        if (!string.IsNullOrEmpty(catalog.Namespace))
        {
            source.Append("namespace ").Append(catalog.Namespace).AppendLine();
            source.AppendLine("{");
        }

        var indent = string.IsNullOrEmpty(catalog.Namespace) ? string.Empty : "    ";
        source.Append(indent).Append("public sealed class ").Append(extensionName).AppendLine();
        source.Append(indent).Append("    : global::AtomUI.Localization.LanguageResourceExtension<")
              .Append(catalog.TypeName).AppendLine(">");
        source.Append(indent).AppendLine("{");
        source.Append(indent).Append("    public ").Append(extensionName).AppendLine("()");
        source.Append(indent).AppendLine("    {");
        source.Append(indent).AppendLine("    }");
        source.AppendLine();
        source.Append(indent).Append("    public ").Append(extensionName).AppendLine("(");
        source.Append(indent).Append("        ").Append(catalog.TypeName).AppendLine(" kind)");
        source.Append(indent).AppendLine("        : base(kind)");
        source.Append(indent).AppendLine("    {");
        source.Append(indent).AppendLine("    }");
        source.Append(indent).AppendLine("}");

        if (!string.IsNullOrEmpty(catalog.Namespace))
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static string GetExtensionName(string metadataName)
    {
        var namespaceSeparator = metadataName.LastIndexOf('.');
        var containingTypeSeparator = metadataName.LastIndexOf('+');
        var separator = Math.Max(namespaceSeparator, containingTypeSeparator);
        var typeName = separator < 0 ? metadataName : metadataName.Substring(separator + 1);
        return typeName.EndsWith("Kind", StringComparison.Ordinal)
            ? typeName.Substring(0, typeName.Length - "Kind".Length) + "Extension"
            : typeName + "Extension";
    }

    internal static string GetRegistrationTypeName(string catalogId)
    {
        const ulong offsetBasis = 14695981039346656037UL;
        const ulong prime = 1099511628211UL;
        var hash = offsetBasis;
        foreach (var character in catalogId)
        {
            hash ^= character;
            hash = unchecked(hash * prime);
        }

        return "GeneratedLanguageCatalog_" + hash.ToString("X16", CultureInfo.InvariantCulture);
    }

    private static string BuildRegistrationSource(
        string? assemblyName,
        CompiledLanguageCatalog compiledCatalog)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.Append("namespace ")
              .Append(GeneratedThemeSchemaWriter.GetGeneratedNamespace(assemblyName))
              .AppendLine();
        source.AppendLine("{");
        source.Append("    internal static class ")
              .Append(GetRegistrationTypeName(compiledCatalog.Catalog.CatalogId))
              .AppendLine();
        source.AppendLine("    {");
        source.AppendLine("        internal static void Register(global::AtomUI.Localization.ILocalizationBuilder builder)");
        source.AppendLine("        {");
        source.AppendLine("            global::System.ArgumentNullException.ThrowIfNull(builder);");
        LanguageModuleSourceWriter.WriteCatalog(source, compiledCatalog, "            ");
        foreach (var bundle in compiledCatalog.Bundles.Where(static bundle =>
                     bundle.SourceKind == Xliff.LanguageFileSourceKind.ModuleBuiltIn))
        {
            LanguageModuleSourceWriter.WriteBundle(
                source,
                compiledCatalog.Catalog,
                bundle,
                "            ");
        }
        source.AppendLine("        }");
        source.AppendLine("    }");
        source.AppendLine("}");
        return source.ToString();
    }
}
